"""속성 추출 규칙 (속성 사전 + 절 분리). 여러 ABSA 분석기가 공유.

ABSA = 속성 추출 + 감성 판정. 이 모듈은 '속성 추출'만 담당하고,
'감성 판정'은 분석기마다 다르게 둔다(KoELECTRA / 학습 분류기 / LLM).
"""
import re

aspects = {
    "배송": ["배송", "도착", "택배", "하루만"],
    "품질": ["품질", "성능", "음질", "튼튼", "내구", "마감", "보온", "밑창", "연결"],
    "가격": ["가격", "가성비", "비싸", "저렴", "값", "부담"],
    "포장": ["포장", "박스", "흠집", "파손"],
    "디자인": ["디자인", "예쁘", "예뻐", "이쁘", "색상", "깔끔"],
    "CS": ["문의", "응대", "교환", "환불", "고객"],
}


# 문장 → 절 단위로 쪼갬 (지만/는데/고 등에서 끊어 속성별 감성이 안 섞이게)
def clauses(text):
    out = []
    for s in re.split(r"[.!?\n]", text):
        for c in re.split(r"(?<=지만)\s*|(?<=는데)\s*|(?<=으나)\s*|(?<=고)\s+|(?<=며)\s+", s):
            if c.strip():
                out.append(c.strip())
    return out


# 절에 등장한 속성들
def detect(s):
    return [a for a, kws in aspects.items() if any(k in s for k in kws)]


# 감성 분류 전에 끝 연결어미 제거 (분류 정확도↑)
def strip_conj(s):
    return re.sub(r"(지만|는데|으나|고|며)$", "", s)
